const DICTS = { it: IT, en: EN };

export function t(key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[lang()][key] ?? DICTS.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, String(vars[k]));
  return s;
}
/** Plural: 'cat.results' + n → 'cat.results.one' / 'cat.results.other' ({n} interpolated). */
export function tp(base: string, n: number, vars?: Record<string, string | number>): string {
  return t(`${base}.${n === 1 ? 'one' : 'other'}`, { n: n.toLocaleString(), ...vars });
}
